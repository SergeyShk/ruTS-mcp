def diversity_group(analysis: Analysis) -> GroupResult:
    """
    Меры лексического разнообразия текста с их описаниями

    Описание:
        Меры DiversityStats из ruTS по словоформам в нижнем регистре; описание
        меры говорит, в какую сторону растет богатство словаря и как мера
        ведет себя на текстах разной длины, если это называет документация
        ruTS или anyTS. По Zenker и Kyle (2021) MATTR, MTLD и HD-D
        устойчивы на текстах от 50-200 слов, поэтому текст короче 200 слов
        получает предупреждение. Меры, которые на тексте не определены (nan
        или бесконечность), отдаются как None и перечисляются в предупреждении

    Ссылки:
        https://doi.org/10.1016/j.asw.2020.100505

    Аргументы:
        analysis (Analysis): Текст и настройки

    Вывод:
        tuple[dict[str, Any], list[str]]: Имя меры ruTS - ее значение и описание;
            предупреждения

    Исключения:
        SourceError: Если в тексте нет слов

    Пример использования:
        >>> stats, warnings = diversity_group(Analysis("Мама мыла раму, а папа мыл раму."))
        >>> stats["ttr"]["value"], stats["hdd"]["value"]
        (0.8571, None)
    """
    from ruts import DiversityStats

    ds = DiversityStats(analysis.text)
    values = ds.get_stats()
    stats = {
        name: stat(values[name], description) for name, description in DIVERSITY_STATS.items()
    }
    n_words = len(ds.words)
    warnings = []
    if n_words < MIN_WORDS:
        warnings.append(
            f"Слов в тексте: {n_words}, меньше {MIN_WORDS}: меры лексического разнообразия "
            "на таком тексте неустойчивы, сравнивать по ним тексты нельзя"
        )
    elif n_words < STABLE_WORDS:
        warnings.append(
            f"Слов в тексте: {n_words}, меньше {STABLE_WORDS}. По Zenker и Kyle (2021) MATTR, "
            f"MTLD и HD-D устойчивы на текстах от {MIN_WORDS}-{STABLE_WORDS} слов, а MA-MTLD, "
            "MTLD-W и мера Мааса на коротких текстах неустойчивы: сравнивайте тексты "
            "по MATTR, MTLD и HD-D"
        )
    warnings += undefined_warnings(
        stats,
        "формула меры не определена на таком распределении слов: слишком мало слов, "
        "нет повторов или нет слов, встреченных один или два раза",
    )
    return stats, warnings
