from typing import Annotated, Any

from pydantic import Field

from .analysis import Analysis, Options, Preset
from .errors import ruts_errors
from .groups import DEFAULT_GROUPS, GROUPS, Group
from .inputs import PATH, TEXT, load_ruts, read_source
from .language import language_warnings


def analyze_text(
    text: Annotated[str, Field(description=TEXT)] = "",
    path: Annotated[str | None, Field(description=PATH)] = None,
    groups: Annotated[
        tuple[Group, ...],
        Field(description="Группы статистик; каждая - ключ результата", min_length=1),
    ] = DEFAULT_GROUPS,
    distributions: Annotated[
        bool,
        Field(
            description="Добавить распределения слов по числу букв и слогов "
            "и знаков препинания по типам (группа basic)"
        ),
    ] = False,
    readability_preset: Annotated[
        Preset,
        Field(
            description="Коэффициенты теста Флеша-Кинкайда (у academic - и индекса Флеша), "
            "группа readability: plainrussian откалиброван по школьным классам и подходит "
            "для любых текстов, в том числе художественных; fiction - коэффициенты Оборневой "
            "по художественным текстам, дает класс на несколько лет выше; academic - "
            "Соловьёва, Иванова и Солнышкиной по учебникам 5-11 классов. Без особой причины "
            "оставляйте plainrussian"
        ),
    ] = "plainrussian",
    descriptions: Annotated[
        bool,
        Field(
            description="Добавить к статистикам описания; false - короче ответ, когда "
            "описания уже известны по прошлому вызову"
        ),
    ] = True,
) -> dict[str, Any]:
    """Измерить русский текст статистиками библиотеки ruTS.

    Используйте, чтобы получить точные числа о тексте, а не оценивать его на глаз. Считаются только запрошенные группы. Текст из файла передавайте через path, а не пересылайте целиком: так быстрее, и статистики считаются по исходному тексту.

    Группы статистик:
    - basic: предложения, слова, слоги, символы, буквы, пробелы и знаки препинания; уникальные, длинные (от 6 букв), сложные (от 4 слогов), простые, односложные и многосложные слова с долей от всех слов.
    - readability: удобочитаемость - сводный класс и формулы Флеша-Кинкайда, Флеша, Колман-Лиау, SMOG, ARI, LIX, RIX, Соловьёва-Иванова-Солнышкиной, Мацковского, Дейла-Чейла и Ганнинга с переводом в класс школы и возраст читателя, время чтения.
    - diversity: лексическое разнообразие - TTR и поправки к нему, MATTR, MSTTR, MTLD, HD-D, индексы Симпсона, Юла и Оноре, энтропия, законы Ципфа и Хипса.
    - morph: морфология по pymorphy3 без снятия омонимии - части речи и 12 грамматических признаков (число и доля слов с каждым значением) и доли форм глагола: наклонения, инфинитив, причастия, деепричастия, совершенный вид, страдательные и возвратные формы.
    - phon: фоностатистики по буквам, без ударения, оглушения и редукции - доли гласных, сонорных, звонких и глухих согласных, тяжелые сочетания согласных, зияния, жесткость, открытые слоги, индексы аллитерации и ассонанса.
    - cohesion: связность по образцу Coh-Metrix - повторы существительных, аргументов и знаменательных слов между предложениями, местоимения, данность, повтор времени и вида, коннекторы по классам на 1000 слов.
    - lexical: лексическая сложность по частотам языка - доля слов, найденных в частотном словаре Ляшевской и Шарова, средняя частотность (ipm) и ее логарифм, диапазон и дисперсия по корпусу, сюрпризал и перплексия, доли слов из 1000-10000 самых частых лемм, лексическая плотность. Метрикам по словарю нужен скачанный словарь.
    - verse: стих - строки и строфы, метр и число стоп, отклонения от метра и пропуски ударений, доля рифмованных строк и схемы рифмовки, мужские, женские и дактилические окончания. Нужен скачанный словарь ударений.
    - syntax: синтаксис по дереву зависимостей модели spaCy - длина зависимостей, глубина и ветвистость дерева, валентность глаголов, клаузы и придаточные, сочинительные цепочки, модификаторы существительного, цепочки родительных падежей, причастные и деепричастные обороты, пассив, инфинитивы, отрицания, расщепленные сказуемые («оказать помощь»), отношение существительных к глаголам. Нужна скачанная модель spaCy; на длинном тексте разбор занимает секунды.
    - style: SEO-метрики по словоформам - классическая и академическая тошнота, водность, заспамленность и естественность по Ципфу с прочтением по нормам Advego, Text.ru, pr-cy и megaindex (нормы рассчитаны на тексты сайтов в несколько сотен слов, к художественной прозе неприменимы), самые частые словоформы, лексические маркеры канцелярита с найденными словами и фразами: отглагольные существительные, производные предлоги, вводные слова, штампы. Синтаксические маркеры канцелярита - расщепленные сказуемые, цепочки родительных падежей, пассив, отношение существительных к глаголам - в группе syntax: для проверки на канцелярит берите style и syntax.

    В результате по ключу на каждую запрошенную группу: статистика с ее значением "value", долей "share" или прочтением по шкале "interpretation", если они есть, и описанием "description" - что она считает; у маркеров канцелярита группы style еще число вхождений "count" и найденные слова и фразы "found". Значение null - статистика на этом тексте не определена. Ключ "warnings" - причины, по которым значения могут быть неустойчивы или не иметь смысла для этого текста: короткий текст, текст не на русском языке, не скачанные словари или модель (тогда предупреждение называет команду, которая их скачивает). Прочитайте предупреждения, прежде чем делать выводы.
    """
    load_ruts()
    text = read_source(text, path)
    analysis = Analysis(text, Options(distributions=distributions, preset=readability_preset))
    result: dict[str, Any] = {}
    warnings = language_warnings(text)
    with ruts_errors():
        for group in dict.fromkeys(groups):
            result[group], group_warnings = GROUPS[group](analysis)
            warnings += group_warnings
    if not descriptions:
        for stats in result.values():
            for item in stats.values():
                item.pop("description", None)
    return result | {"warnings": warnings}
