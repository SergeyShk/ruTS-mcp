READ_WARNINGS = (
    "Сначала прочитай warnings в ответах инструментов: они говорят, когда значения неустойчивы "
    "или не посчитаны (короткий текст, не скачанные словари или модель). Не делай выводов "
    "по значениям, которые предупреждения ставят под сомнение, и скажи об этом."
)
FROM_CONVERSATION = (
    "Текст для разбора - в предыдущих сообщениях разговора: вставленный текст или приложенный "
    "файл. Если текста там нет, попроси пользователя прислать его и не вызывай инструменты."
)
COMPARE_FROM_CONVERSATION = (
    "Тексты A и B - в предыдущих сообщениях разговора: первый текст - A, второй - B. "
    "Если двух текстов там нет, попроси пользователя прислать их и не вызывай инструменты."
)
TRUNCATED = (
    "Аргумент промпта пришел неполным ({arguments}): клиент, например Claude Code, мог обрезать "
    "его по первому пробелу. {from_conversation} Подскажи, что длинный текст нужно вставлять "
    "сообщением, а промпт вызывать без аргументов."
)


def is_text(argument: str) -> bool:
    """Текст ли в аргументе промпта: одно слово - это обрезанный клиентом аргумент"""
    return len(argument.split()) > 1


def source(text: str) -> str:
    """
    Конец промпта: переданный текст или указание взять его из разговора

    Описание:
        Пустой аргумент значит, что текст уже прислан в разговоре, аргумент
        из одного слова - что клиент обрезал текст; в обоих случаях модель
        берет текст из разговора, а для обрезанного аргумента еще и подсказывает,
        как вызывать промпт

    Аргументы:
        text (str): Текст из аргумента промпта

    Вывод:
        str: Текст под заголовком или указание взять его из разговора

    Пример использования:
        >>> source("Мама мыла раму.")
        'Текст:\\n\\nМама мыла раму.'
        >>> source(" ") == FROM_CONVERSATION
        True
        >>> source('"Мама').startswith('Аргумент промпта пришел неполным ("Мама)')
        True
    """
    if is_text(text):
        return f"Текст:\n\n{text}"
    if not text.strip():
        return FROM_CONVERSATION
    return TRUNCATED.format(arguments=text.strip(), from_conversation=FROM_CONVERSATION)


def readability_review(text: str = "") -> str:
    """Оценить, для какого читателя написан текст, и предложить, как его упростить.

    :param text: Текст на русском языке; не задан - текст из предыдущих сообщений разговора
    """
    return f"""Оцени удобочитаемость текста.

1. Вызови analyze_text с группами basic, readability и syntax.
2. {READ_WARNINGS}
3. По сводному классу и его прочтению назови ступень обучения и возраст читателя. Если формулы класса заметно расходятся, скажи об этом. Шкалы - в ресурсе ruts://scales/readability.
4. Объясни, что делает текст трудным: длина предложений, длинные и сложные слова, длина зависимостей и глубина дерева, придаточные и обороты. Опирайся на значения, а не на впечатление.
5. Предложи конкретные правки с цитатами из текста: какие предложения разбить, какие слова заменить.

{source(text)}"""


def officialese_review(text: str = "") -> str:
    """Найти в тексте канцелярит и предложить живые замены.

    :param text: Текст на русском языке; не задан - текст из предыдущих сообщений разговора
    """
    return f"""Проверь текст на канцелярит.

1. Вызови analyze_text с группами style и syntax.
2. {READ_WARNINGS}
3. Оцени маркеры канцелярита: отглагольные существительные, производные предлоги, вводные слова и штампы (style), расщепленные сказуемые, цепочки родительных падежей, пассив и отношение существительных к глаголам (syntax).
4. Найди в тексте конкретные примеры этих конструкций; чтобы показать все вхождения слова, вызови kwic.
5. Для каждого примера предложи живую замену: «оказать помощь» - «помочь», «в целях повышения» - «чтобы повысить».

{source(text)}"""


def verse_review(text: str = "") -> str:
    """Разобрать стихотворение: метр, рифму, окончания строк и звукопись.

    :param text: Текст на русском языке; не задан - текст из предыдущих сообщений разговора
    """
    return f"""Разбери стихотворение.

1. Вызови analyze_text с группами verse и phon.
2. {READ_WARNINGS}
3. Назови метр и число стоп, оцени отклонения от метра и пропуски ударений; если метр не определен, предположи, что это за стих (дольник, акцентный стих, верлибр).
4. Опиши рифмовку по схемам строф и окончания строк: мужские, женские, дактилические.
5. Оцени звукопись по индексам аллитерации и ассонанса и приведи строки, где она слышна.

{source(text)}"""


def seo_review(text: str = "") -> str:
    """Проверить текст для сайта по SEO-метрикам и найти его ключевые слова.

    :param text: Текст на русском языке; не задан - текст из предыдущих сообщений разговора
    """
    return f"""Проверь текст для сайта по SEO-метрикам.

1. Вызови analyze_text с группой style и keyness без reference: эталоном станет частотный словарь русского языка.
2. {READ_WARNINGS}
3. Сравни тошноту, водность, заспамленность и естественность по Ципфу с нормами сервисов (прочтение в ответе, полосы - в ресурсе ruts://scales/style). Помни, что нормы рассчитаны на тексты сайтов в несколько сотен слов.
4. По ключевым словам скажи, о чем текст для поисковой системы, и какие слова повторяются слишком часто.
5. Предложи правки: что сократить, какие повторы заменить синонимами.

{source(text)}"""


def compare_review(text_a: str = "", text_b: str = "") -> str:
    """Сравнить два текста по стилю и лексике.

    :param text_a: Первый текст (A); не задан - тексты из предыдущих сообщений разговора
    :param text_b: Второй текст (B); не задан - тексты из предыдущих сообщений разговора
    """
    if is_text(text_a) and is_text(text_b):
        texts = f"Текст A:\n\n{text_a}\n\nТекст B:\n\n{text_b}"
    elif text_a.strip() or text_b.strip():
        arguments = ", ".join(
            argument.strip() for argument in (text_a, text_b) if argument.strip()
        )
        texts = TRUNCATED.format(arguments=arguments, from_conversation=COMPARE_FROM_CONVERSATION)
    else:
        texts = COMPARE_FROM_CONVERSATION
    return f"""Сравни два текста по стилю и лексике.

1. Вызови compare_texts с a = [текст A] и b = [текст B]. Окно короче половины window отбрасывается, а для сравнения нужно хотя бы по два окна в каждом тексте. Поэтому, если в более коротком тексте меньше 1500 слов, возьми window, равное половине числа его слов, но не меньше 100 (число слов дает analyze_text с группой basic). Если в нем меньше 150 слов, compare_texts не подойдет: сравни результаты analyze_text для обоих текстов.
2. Вызови keyness с текстом A и reference = текст B, затем с positive = false: это слова, которые в A чаще и реже, чем в B.
3. {READ_WARNINGS} По одному тексту на корпус различия могут быть особенностями текста, а не автора или жанра.
4. Опиши главные различия по признакам с наибольшей по модулю дельтой Клиффа и по ключевым словам, с цитатами из обоих текстов.

{texts}"""
